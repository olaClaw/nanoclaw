/** Fail-closed preflight for the legacy agent image's local Docker context. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ALLOWED = [
  'Dockerfile',
  '.dockerignore',
  'agent-runner/package.json',
  'agent-runner/bun.lock',
  'cli-tools.json',
  'install-cli-tools.sh',
  'entrypoint.sh',
];

const IGNORE_RULES =
  [
    '**',
    '!Dockerfile',
    '!.dockerignore',
    '!agent-runner/',
    '!agent-runner/package.json',
    '!agent-runner/bun.lock',
    '!cli-tools.json',
    '!install-cli-tools.sh',
    '!entrypoint.sh',
  ].join('\n') + '\n';

const TEMP_PREFIX = 'nanoclaw-agent-context-';
const TEMP_MARKER = '.nanoclaw-generated-context';
const TEMP_MARKER_CONTENT = 'generated by privacy-agent-context.mjs\n';

const FORBIDDEN = [
  ['email-shaped value', /\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b/],
  [
    'credential-shaped value',
    /aoc_[A-Za-z0-9_-]{16,}|[0-9]{6,}:[A-Za-z0-9_-]{20,}|(?:sk-|ghp_|github_pat_)[A-Za-z0-9_-]{16,}|BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY/,
  ],
  ['credential assignment', /(?:password|passwd|api[_-]?key|secret|token)\s*[:=]\s*['"]?[A-Za-z0-9_+./-]{12,}/i],
];

function hasIpv4Address(content) {
  for (const match of content.matchAll(/(?<!\d)(?:\d{1,3}\.){3}\d{1,3}(?!\d)/g)) {
    if (match[0].split('.').every((part) => Number(part) <= 255)) return true;
  }
  return false;
}

function hasPrivateEndpoint(content) {
  for (const match of content.matchAll(/https?:\/\/[^\s'"`<>]+/g)) {
    try {
      const host = new URL(match[0]).hostname.toLowerCase();
      if (host === 'localhost' || /\.(?:local|lan|internal)$/.test(host)) return true;
    } catch {
      // URL-like documentation text is not a real endpoint.
    }
  }
  return false;
}

export function checkAgentContext(contextRoot) {
  const issues = [];
  const rootStat = fs.lstatSync(contextRoot, { throwIfNoEntry: false });
  if (!rootStat?.isDirectory() || rootStat.isSymbolicLink()) {
    return ['context root is missing or is not a regular directory'];
  }
  const runnerDir = path.join(contextRoot, 'agent-runner');
  const runnerStat = fs.lstatSync(runnerDir, { throwIfNoEntry: false });
  if (!runnerStat?.isDirectory() || runnerStat.isSymbolicLink()) {
    return ['agent-runner: missing directory or symlink'];
  }
  if (fs.lstatSync(path.join(contextRoot, 'Dockerfile.dockerignore'), { throwIfNoEntry: false })) {
    issues.push('Dockerfile-specific ignore file overrides the reviewed allowlist');
  }
  const ignorePath = path.join(contextRoot, '.dockerignore');
  const ignoreStat = fs.lstatSync(ignorePath, { throwIfNoEntry: false });
  if (!ignoreStat?.isFile() || ignoreStat.isSymbolicLink() || fs.readFileSync(ignorePath, 'utf8') !== IGNORE_RULES) {
    issues.push('.dockerignore differs from the reviewed allowlist');
  }

  for (const relative of ALLOWED) {
    const full = path.join(contextRoot, relative);
    let stat;
    try {
      stat = fs.lstatSync(full);
    } catch {
      issues.push(`${relative}: required file missing`);
      continue;
    }
    if (!stat.isFile() || stat.isSymbolicLink()) {
      issues.push(`${relative}: not a regular file`);
      continue;
    }
    if (stat.size > 16 * 1024 * 1024) {
      issues.push(`${relative}: unexpected file size`);
      continue;
    }
    const buffer = fs.readFileSync(full);
    if (buffer.includes(0)) {
      issues.push(`${relative}: binary content not reviewed`);
      continue;
    }
    const content = buffer.toString('utf8');
    if (hasIpv4Address(content)) issues.push(`${relative}: IP address`);
    if (hasPrivateEndpoint(content)) issues.push(`${relative}: private endpoint`);
    for (const [category, pattern] of FORBIDDEN) {
      if (pattern.test(content)) issues.push(`${relative}: ${category}`);
    }
  }

  const dockerfile = path.join(contextRoot, 'Dockerfile');
  const dockerfileStat = fs.lstatSync(dockerfile, { throwIfNoEntry: false });
  if (dockerfileStat?.isFile() && !dockerfileStat.isSymbolicLink()) {
    const content = fs.readFileSync(dockerfile, 'utf8');
    const copySources = new Set(ALLOWED.filter((name) => name !== 'Dockerfile' && name !== '.dockerignore'));
    for (const line of content.split('\n')) {
      const trimmed = line.trim();
      if (/^ADD\b/i.test(trimmed)) issues.push('Dockerfile: ADD is not reviewed');
      if (!/^COPY\b/i.test(trimmed)) continue;
      const parts = trimmed.split(/\s+/).slice(1);
      if (parts.length < 2 || parts.some((part) => part.startsWith('--'))) {
        issues.push('Dockerfile: unsupported COPY form');
        continue;
      }
      for (const source of parts.slice(0, -1)) {
        if (!copySources.has(source)) issues.push('Dockerfile: COPY source outside allowlist');
      }
    }
  }
  return issues;
}

export function stageAgentContext(contextRoot) {
  const issues = checkAgentContext(contextRoot);
  if (issues.length) throw new Error(`Agent context preflight failed: ${issues.join('; ')}`);
  const staged = fs.mkdtempSync(path.join(os.tmpdir(), TEMP_PREFIX));
  fs.writeFileSync(path.join(staged, TEMP_MARKER), TEMP_MARKER_CONTENT, { mode: 0o600 });
  try {
    fs.mkdirSync(path.join(staged, 'agent-runner'));
    for (const relative of ALLOWED) {
      fs.copyFileSync(path.join(contextRoot, relative), path.join(staged, relative));
    }
    if (checkAgentContext(staged).length) throw new Error('Staged agent context did not pass its own preflight');
    return staged;
  } catch (error) {
    cleanupAgentContext(staged);
    throw error;
  }
}

export function cleanupAgentContext(staged) {
  const resolved = path.resolve(staged);
  const parent = path.dirname(resolved);
  if (fs.realpathSync(parent) !== fs.realpathSync(os.tmpdir()) || !path.basename(resolved).startsWith(TEMP_PREFIX)) {
    throw new Error('Refusing to remove a directory that is not a generated agent context');
  }
  const stat = fs.lstatSync(resolved, { throwIfNoEntry: false });
  if (!stat?.isDirectory() || stat.isSymbolicLink()) {
    throw new Error('Refusing to remove a directory that is not a generated agent context');
  }
  const marker = path.join(resolved, TEMP_MARKER);
  const markerStat = fs.lstatSync(marker, { throwIfNoEntry: false });
  if (!markerStat?.isFile() || markerStat.isSymbolicLink() || fs.readFileSync(marker, 'utf8') !== TEMP_MARKER_CONTENT) {
    throw new Error('Refusing to remove a directory that is not a generated agent context');
  }
  fs.rmSync(resolved, { recursive: true, force: false });
}

const invokedAsScript = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedAsScript) {
  try {
    if (process.argv[2] === '--cleanup') {
      if (!process.argv[3]) throw new Error('Generated context path required');
      cleanupAgentContext(process.argv[3]);
    } else {
      const stage = process.argv[2] === '--stage';
      const root = path.resolve(
        (stage ? process.argv[3] : process.argv[2]) ??
          path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'container'),
      );
      if (stage) {
        process.stdout.write(`${stageAgentContext(root)}\n`);
      } else {
        const issues = checkAgentContext(root);
        if (issues.length) {
          for (const issue of issues) process.stderr.write(`privacy gate: ${issue}\n`);
          process.exitCode = 1;
        } else {
          process.stdout.write('privacy gate: agent build context preflight passed\n');
        }
      }
    }
  } catch (error) {
    process.stderr.write(`privacy gate: ${error instanceof Error ? error.message : 'unexpected error'}\n`);
    process.exitCode = 1;
  }
}
